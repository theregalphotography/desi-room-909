import legacyEventsData from "@/data/legacy-events.json";
import { fetchAllTicketTailorEvents } from "@/lib/tickettailor";

/**
 * Provider-neutral event shape used by every page and component. The
 * ticketing provider (currently Ticket Tailor, see lib/tickettailor.ts) maps
 * its own payload into this, so UI code never touches provider fields.
 */
export interface TicketEvent {
  id: string;
  name: string;
  summary: string;
  startUtc: string;
  endUtc: string;
  /** IANA time zone the event's own dates are displayed in. */
  timezone: string;
  venueName: string;
  venueAddress: string;
  posterUrl: string | null;
  /** Checkout page opened inside the on-site popup. Empty for legacy events. */
  checkoutUrl: string;
  hasAvailableTickets: boolean;
}

/**
 * One-time snapshot of past events that ran on Eventbrite before the move to
 * Ticket Tailor (generated by `npm run snapshot:eventbrite`). Never changes;
 * merged into the "Rooms We Left Behind" list below.
 */
const LEGACY_EVENTS = legacyEventsData as TicketEvent[];

function sortByStartAsc(events: TicketEvent[]): TicketEvent[] {
  return [...events].sort((a, b) => new Date(a.startUtc).getTime() - new Date(b.startUtc).getTime());
}

/** Upcoming = events whose end date/time is still in the future, soonest first. */
export async function getUpcomingEvents(): Promise<TicketEvent[]> {
  const now = Date.now();
  const events = await fetchAllTicketTailorEvents();
  return sortByStartAsc(events).filter((event) => new Date(event.endUtc).getTime() > now);
}

/**
 * Past = ended Ticket Tailor events plus the legacy Eventbrite snapshot, most
 * recently ended first. If Ticket Tailor is unreachable the legacy history
 * still renders rather than the whole section disappearing.
 */
export async function getPastEvents(): Promise<TicketEvent[]> {
  const now = Date.now();
  let live: TicketEvent[] = [];
  try {
    live = await fetchAllTicketTailorEvents();
  } catch (error) {
    console.error("[events] Ticket Tailor fetch failed for past events:", error);
  }
  const liveIds = new Set(live.map((event) => event.id));
  const merged = [...live, ...LEGACY_EVENTS.filter((event) => !liveIds.has(event.id))];
  return sortByStartAsc(merged)
    .filter((event) => new Date(event.endUtc).getTime() <= now)
    .reverse();
}

/** Pure selection helper over an already-fetched, sorted upcoming list. */
export function selectHeroEvent(upcoming: TicketEvent[]): TicketEvent | null {
  return upcoming[0] ?? null;
}

export function formatEventDateBadge(startIso: string, timeZone: string): string {
  const date = new Date(startIso);
  const weekday = new Intl.DateTimeFormat("en-US", { weekday: "short", timeZone }).format(date).toUpperCase();
  const monthDay = new Intl.DateTimeFormat("en-US", { month: "short", day: "numeric", year: "numeric", timeZone })
    .format(date)
    .toUpperCase();
  const time = new Intl.DateTimeFormat("en-US", { hour: "numeric", timeZone }).format(date).replace(" ", "");
  return `${weekday} · ${monthDay} · ${time}`;
}

export function formatShortEventDate(startIso: string, timeZone: string): string {
  const date = new Date(startIso);
  const weekday = new Intl.DateTimeFormat("en-US", { weekday: "short", timeZone }).format(date).toUpperCase();
  const monthDay = new Intl.DateTimeFormat("en-US", { month: "short", day: "numeric", timeZone })
    .format(date)
    .toUpperCase();
  return `${weekday} ${monthDay}`;
}

export function formatEventTimeRange(startIso: string, endIso: string, timeZone: string): string {
  const formatter = new Intl.DateTimeFormat("en-US", { hour: "numeric", minute: "2-digit", timeZone });
  return `${formatter.format(new Date(startIso))} – ${formatter.format(new Date(endIso))}`;
}

export function formatPastEventDate(endIso: string, timeZone: string): string {
  const date = new Date(endIso);
  return new Intl.DateTimeFormat("en-US", { month: "short", day: "numeric", year: "numeric", timeZone })
    .format(date)
    .toUpperCase();
}
